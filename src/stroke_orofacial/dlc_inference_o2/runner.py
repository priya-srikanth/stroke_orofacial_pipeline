"""Generate the DLC inference runner script for O2.

Ported from cell 6 of canonical notebook
``20251112_DLC_batch_video_analysis_O2.ipynb`` (Rule 1: latest YYYYMMDD).

The generated ``run_dlc_batch.py`` script is a self-contained Python file
that runs on O2 with the ``deeplabcut`` conda env. It:
  1. Reads a YAML selection file for animal/date include/exclude.
  2. Discovers ``video2_*.avi`` files under the input root.
  3. Runs ``deeplabcut.analyze_videos()`` + ``deeplabcut.filterpredictions()``
     per video (one at a time to minimize RAM spikes).
  4. Skips videos whose outputs already exist (``--skip_if_exists``).
"""

from __future__ import annotations


def generate_inference_script() -> str:
    """Return the complete ``run_dlc_batch.py`` source code as a string.

    This is a standalone script that runs on O2 — it imports ``deeplabcut``
    and ``yaml`` which are available in the O2 conda env but NOT in the
    local ``frsb`` env.
    """
    return r'''#!/usr/bin/env python3
"""DLC batch inference runner. Runs on O2 GPU nodes.

Generated by stroke_orofacial.dlc_inference_o2.runner.
Do not edit directly — regenerate from the module.
"""
import argparse, os, re, sys
from pathlib import Path
import yaml
import deeplabcut

DATE_RE = re.compile(r"^\d{8}b?$")


def list_dates(inroot: Path):
    return sorted([p.name for p in inroot.iterdir() if p.is_dir() and DATE_RE.match(p.name)])


def effective_dates_for_animal(animal: str, selection: dict, all_dates):
    spec = (selection.get("animals") or {}).get(animal, {}) or {}
    include = spec.get("include", "all")
    exclude = set(map(str, spec.get("exclude", []))) if spec.get("exclude") else set()
    if include == "all":
        return [d for d in all_dates if d not in exclude]
    else:
        include = list(map(str, include))
        return [d for d in include if d in all_dates and d not in exclude]


def outputs_exist(destroot: Path, animal: str, video_stem: str) -> bool:
    outdir = destroot / animal
    h5 = list(outdir.glob(f"*{video_stem}*DLC*.h5"))
    csv = list(outdir.glob(f"*{video_stem}*DLC*.csv"))
    return bool(h5 or csv)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--inroot", required=True)
    ap.add_argument("--outroot", required=True)
    ap.add_argument("--selection-yaml", required=True)
    ap.add_argument("--videoglob", default="video2_*.avi")
    ap.add_argument("--shuffle", type=int, default=5)
    ap.add_argument("--trainingsetindex", type=int, default=0)
    ap.add_argument("--gputouse", type=int, default=0)
    ap.add_argument("--batchsize", type=int, default=1)
    ap.add_argument("--allow_growth", action="store_true")
    ap.add_argument("--skip_if_exists", action="store_true")
    ap.add_argument("--dryrun", action="store_true")
    args = ap.parse_args()

    cfg_path = Path(args.config).as_posix()
    inroot = Path(args.inroot)
    outroot = Path(args.outroot)
    outroot.mkdir(parents=True, exist_ok=True)

    with open(args.selection_yaml, "r", encoding="utf-8") as f:
        selection = yaml.safe_load(f) or {}
    animals = sorted((selection.get("animals") or {}).keys())
    if not animals:
        print("[ERROR] No animals found in selection YAML."); sys.exit(2)

    all_dates = list_dates(inroot)
    print(f"Found {len(all_dates)} date folders under {inroot}")

    to_process = []
    for animal in animals:
        eff_dates = effective_dates_for_animal(animal, selection, all_dates)
        for d in eff_dates:
            vdir = inroot / d / animal
            if not vdir.is_dir():
                print(f"[WARN] {animal}: date folder missing: {vdir}")
                continue
            for v in sorted(vdir.glob(args.videoglob)):
                if args.skip_if_exists and outputs_exist(outroot, animal, v.stem):
                    print(f"[SKIP] output exists for: {animal} {d} {v.name}")
                    continue
                to_process.append((animal, d, v.as_posix()))

    if not to_process:
        print("No videos to process."); sys.exit(0)

    print(f"Total videos to process: {len(to_process)}")
    if args.dryrun:
        for (animal, d, v) in to_process:
            print("[DRY] would process:", animal, d, v)
        sys.exit(0)

    for (animal, d, vpath) in to_process:
        dest_animal = (outroot / animal).as_posix()
        Path(dest_animal).mkdir(parents=True, exist_ok=True)
        print(f"\n[RUN] analyze_videos -> {vpath}  (dest={dest_animal})")
        try:
            deeplabcut.analyze_videos(
                cfg_path, [vpath], videotype="avi",
                shuffle=args.shuffle, trainingsetindex=args.trainingsetindex,
                gputouse=args.gputouse, save_as_csv=True,
                destfolder=dest_animal, cropping=None,
                batchsize=args.batchsize, allow_growth=args.allow_growth,
                use_shelve=True, save_as_df=True,
            )
        except Exception as e:
            print(f"[ERROR] analyze_videos failed for {vpath}: {e}")
            continue

        print(f"[RUN] filterpredictions -> {vpath}")
        try:
            deeplabcut.filterpredictions(
                cfg_path, [vpath], videotype="avi",
                shuffle=args.shuffle, trainingsetindex=args.trainingsetindex,
                save_as_csv=True, destfolder=dest_animal,
            )
        except Exception as e:
            print(f"[ERROR] filterpredictions failed for {vpath}: {e}")

    print("\n=== Batch complete ===")


if __name__ == "__main__":
    main()
'''
