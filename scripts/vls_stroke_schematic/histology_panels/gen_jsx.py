"""Write build_PS46-55_histology.jsx next to the panels: run it in Illustrator (File > Scripts > Other Script...).
It places and embeds every panel SVG on a layer per animal, adds labels, and saves Histology_behavior_animals_PS46-55.ai."""
import json, os, sys
D = sys.argv[1]; man = json.load(open(f'{D}/manifest.json'))
BREG = {20: 1.34, 21: 1.18, 22: 1.10, 23: 0.98, 24: 0.86, 25: 0.74, 26: 0.62, 27: 0.50, 28: 0.38, 29: 0.26, 30: 0.14,
        31: 0.02, 32: -0.10, 33: -0.22, 34: -0.34, 35: -0.46, 36: -0.58, 37: -0.70, 38: -0.82, 39: -0.94, 40: -1.06,
        41: -1.22, 42: -1.34, 43: -1.46, 44: -1.58, 45: -1.70, 46: -1.82, 47: -1.94, 48: -2.06, 49: -2.18, 50: -2.30}
ORDER = ['PS47', 'PS48', 'PS49', 'PS50', 'PS46', 'PS51', 'PS54', 'PS55']
NAME = {'PS47': 'Mild #1 (PS47)', 'PS48': 'Mild #2 (PS48)', 'PS49': 'Mild #3 (PS49)', 'PS50': 'Mild #4 (PS50)',
        'PS46': 'Moderate #1 (PS46)', 'PS51': 'Moderate #2 (PS51)', 'PS54': 'Severe #1 (PS54)', 'PS55': 'Severe #2 (PS55)'}
PTMM, GAP, ROWH, ZPTMM = 11.0, 8.0, 100.0, 27.6   # points per mm (whole sections, one shared scale: caudal sections come out larger), gap, row height, points per mm for zooms
items = []; y = 0.0
for a in ORDER:
    recs = [r for r in man.values() if r['animal'] == a]
    st = sorted([r for r in recs if r['row'] == 'striatum'], key=lambda r: r['atlas_fig'])
    th = sorted([r for r in recs if r['row'] == 'thalamus'], key=lambda r: (r.get('atlas_fig') or 99, int(r['pick'].split(':e')[1])))
    x = 140.0
    for r in st + th:
        cap = (f"{BREG[r['atlas_fig']]:+.2f} mm" if r.get('atlas_fig') else 'thalamus') + f"  {r['pick'].split(':')[1]}"
        w = r['whole_px'][0] * r['um_px'] / 1000 * PTMM
        items.append(dict(layer=NAME[a], file=r['files']['whole'], x=x, y=y, w=w, cap=cap)); x += w + GAP
    items.append(dict(layer=NAME[a], text=NAME[a], x=0, y=y - 30))
    y -= ROWH
y -= 20
for a in ORDER:                                          # thalamus zooms, +/- GFAP, one row per animal that has them
    th = sorted([r for r in man.values() if r['animal'] == a and r['row'] == 'thalamus'], key=lambda r: (r.get('atlas_fig') or 99, int(r['pick'].split(':e')[1])))
    if not th: continue
    x = 140.0
    for r in th:
        for k in ('zoom', 'zoom_noGFAP'):
            items.append(dict(layer=NAME[a] + ' thalamus zoom', file=r['files'][k], x=x, y=y, w=5.8 * ZPTMM,
                              cap=(f"{BREG[r['atlas_fig']]:+.2f} mm  " if r.get('atlas_fig') else '') + f"{r['pick'].split(':')[1]} {'+GFAP' if k == 'zoom' else 'no GFAP'}")); x += 5.8 * ZPTMM + GAP
    items.append(dict(layer=NAME[a] + ' thalamus zoom', text=NAME[a], x=0, y=y - 40)); y -= 4.2 * ZPTMM + 30
js = """// PS46-55 histology panels (DAPI blue, GFAP green, NeuN red; no DARPP32). Generated by ~/hist/gen_jsx.py.
// Run in Illustrator: File > Scripts > Other Script..., pick this file. Panels are imported as artwork; each SVG's scale bar stays a separate editable group.
#target illustrator
var here = File($.fileName).parent;
var items = %s;
var doc = app.documents.add(DocumentColorSpace.RGB, 2400, 2400);
doc.layers[0].name = 'labels';
function layer(n){ try { return doc.layers.getByName(n); } catch(e){ var L = doc.layers.add(); L.name = n; return L; } }
for (var i = 0; i < items.length; i++){
  var it = items[i], L = layer(it.layer);
  if (it.text){ var t = L.textFrames.add(); t.contents = it.text; t.left = it.x; t.top = it.y; t.textRange.characterAttributes.size = 9; continue; }
  var f = new File(here + '/' + it.file); if (!f.exists){ continue; }
  var p = L.groupItems.createFromFile(f);          // imports the SVG as editable artwork (image + scale-bar group)
  var s = 100 * it.w / p.width; p.resize(s, s, true, true, true, true, s, Transformation.TOPLEFT);
  p.left = it.x; p.top = it.y; p.name = it.file;
  var c = L.textFrames.add(); c.contents = it.cap; c.left = it.x; c.top = it.y + 9; c.textRange.characterAttributes.size = 6;
}
doc.artboards[0].artboardRect = doc.visibleBounds;
var o = new IllustratorSaveOptions(); o.pdfCompatible = true;
doc.saveAs(new File(here.parent.parent + '/Histology_behavior_animals_PS46-55.ai'), o);
alert('Saved Histology_behavior_animals_PS46-55.ai next to your draft');
""" % json.dumps(items, indent=0)
open(f'{D}/build_PS46-55_histology.jsx', 'w').write(js); print(len(items), 'items')
