#!/usr/bin/env python3
"""Stream-parse a large .ipynb and emit a per-cell structure.md.

Usage
-----
    python tools/extract_streaming.py <notebook.ipynb> <output.md> [-n PREVIEW]

Rationale
---------
The Phase 7 canonical DLC notebooks on MICROSCOPE are 400-450 MB each, with
most of that weight being embedded cell-output images. Loading such a
notebook with ``json.load`` risks OOM. This script streams the ipynb cell-
by-cell via ``ijson`` so peak memory stays bounded regardless of notebook
size.

Output markdown lists one section per cell:

* Cell index
* Cell type (code / markdown / raw)
* Source line count
* Preview of the first ``--preview-lines`` non-blank source lines

Cell outputs are deliberately excluded — the purpose of this tool is to
support cell-by-cell classification of notebook *source* into
Production / Exploratory / Deprecated / Ambiguous categories per CLAUDE.md
§"Phase plan requirements" (dead-code identification), and the outputs
contribute nothing to that task.

Requires
--------
``ijson`` (``pip install ijson`` inside the ``stroke_orofacial`` env). If
the env does not already have it, add ``ijson`` to the env requirements
before relying on this tool in CI — currently it is a local dev dependency
only.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import ijson


def _as_str(source) -> str:
    """Normalize a Jupyter cell ``source`` field to a single string.

    Jupyter stores cell source either as a list of lines (each line usually
    terminated with ``\\n``) or, less commonly, as a single string.
    """
    if isinstance(source, list):
        return "".join(source)
    if isinstance(source, str):
        return source
    return ""


def preview_lines(source, n: int) -> list[str]:
    """Return up to ``n`` right-stripped, non-blank source lines."""
    out: list[str] = []
    for line in _as_str(source).splitlines():
        stripped = line.rstrip()
        if stripped.strip():
            out.append(stripped)
            if len(out) >= n:
                break
    return out


def source_line_count(source) -> int:
    """Count source lines, matching what the user would see in Jupyter."""
    text = _as_str(source)
    if not text:
        return 0
    # splitlines() collapses trailing newline correctly — a final "\n" does
    # not add a phantom empty line.
    return len(text.splitlines())


def extract(notebook_path: Path, out_path: Path, preview: int) -> dict:
    """Stream ``notebook_path`` and write a structure summary to ``out_path``.

    Returns a small stats dict ({"cells", "code", "markdown", "raw"}) so
    callers can log totals without re-reading the output markdown.
    """
    counts = {"cells": 0, "code": 0, "markdown": 0, "raw": 0, "other": 0}

    with out_path.open("w", encoding="utf-8") as out:
        out.write(f"# Structure: {notebook_path.name}\n\n")
        out.write(f"Source: `{notebook_path}`\n\n")
        out.write(f"File size: {notebook_path.stat().st_size:,} bytes\n\n")
        out.write(
            "Generated by `tools/extract_streaming.py` for Phase 7 dead-code "
            "classification (see CLAUDE.md §Phase plan requirements and "
            "`docs/prompts/phase-7-dlc-kinematics-kickoff.md`).\n\n"
        )
        out.write("---\n\n")

        with notebook_path.open("rb") as f:
            cells = ijson.items(f, "cells.item")
            for idx, cell in enumerate(cells):
                counts["cells"] += 1
                cell_type = cell.get("cell_type", "<unknown>")
                source = cell.get("source", "")
                n_lines = source_line_count(source)
                preview_list = preview_lines(source, preview)

                if cell_type == "code":
                    counts["code"] += 1
                elif cell_type == "markdown":
                    counts["markdown"] += 1
                elif cell_type == "raw":
                    counts["raw"] += 1
                else:
                    counts["other"] += 1

                out.write(f"## Cell {idx} — {cell_type} ({n_lines} lines)\n\n")

                if preview_list:
                    out.write("```\n")
                    for line in preview_list:
                        out.write(line + "\n")
                    if n_lines > preview:
                        out.write(f"# ... ({n_lines - preview} more lines)\n")
                    out.write("```\n\n")
                else:
                    out.write("_(empty)_\n\n")

        out.write("---\n\n")
        out.write(
            f"**Total cells:** {counts['cells']} "
            f"({counts['code']} code, {counts['markdown']} markdown, "
            f"{counts['raw']} raw"
        )
        if counts["other"]:
            out.write(f", {counts['other']} other")
        out.write(")\n")

    return counts


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("notebook", type=Path, help=".ipynb to extract")
    ap.add_argument("output", type=Path, help="output markdown path")
    ap.add_argument(
        "--preview-lines",
        "-n",
        type=int,
        default=5,
        help="non-blank source lines to preview per cell (default: 5)",
    )
    args = ap.parse_args(argv)

    if not args.notebook.exists():
        print(f"ERROR: notebook not found: {args.notebook}", file=sys.stderr)
        return 2
    args.output.parent.mkdir(parents=True, exist_ok=True)

    counts = extract(args.notebook, args.output, args.preview_lines)
    print(
        f"Wrote {args.output} "
        f"({counts['cells']} cells: {counts['code']} code, "
        f"{counts['markdown']} markdown, {counts['raw']} raw"
        + (f", {counts['other']} other" if counts["other"] else "")
        + ")"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
